"""Pack UI source PNGs and generate the rectangle lookup used by UIImageUtil."""
from pathlib import Path
from tempfile import TemporaryDirectory

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE, MARGIN = 1024, 4


def build(root=ROOT, source=ROOT / "assets/ui-images/source"):
    folder = root / "assets/ui-images"
    shared = root / "src/ReplicatedStorage/Shared"
    paths = sorted(source.glob("*.png"))
    if not paths:
        raise ValueError("No UI source images")
    atlas = Image.new("RGBA", (SIZE, SIZE))
    entries = ["--!strict", "-- Generated by tools/build_ui_atlas.py", "return {"]
    skyline = [0] * SIZE
    tiles = []
    for path in paths:
        with Image.open(path) as source:
            tiles.append((path, source.convert("RGBA")))
    for path, tile in sorted(tiles, key=lambda entry: -entry[1].height):
        w, h = tile.size
        width = w + 2 * MARGIN
        candidates = [x for x in range(SIZE - width + 1) if x == 0 or skyline[x] != skyline[x-1]]
        y, x = min(((max(skyline[x:x+width]), x) for x in candidates), default=(SIZE, 0))
        if y + h + 2 * MARGIN > SIZE:
            raise ValueError(f"UI atlas capacity exceeded at {path.name}")
        if path.stem.endswith("-9slice") and tile.size != (256, 256):
            raise ValueError(f"{path.name} must be 256x256 for the authored slice margins")
        left, top = x + MARGIN, y + MARGIN
        atlas.paste(tile, (left, top))
        slice_center = ", SliceCenter = Rect.new(48, 48, 208, 208)" if path.stem.endswith("-9slice") else ""
        entries.append(f'    ["{path.stem}"] = {{ Atlas = "KeyboardWarriorUI", Offset = Vector2.new({left}, {top}), Size = Vector2.new({w}, {h}){slice_center} }},')
        skyline[x:x+width] = [y + h + 2 * MARGIN] * width
    (folder / "atlas").mkdir(parents=True, exist_ok=True)
    shared.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(dir=root) as temp:
        stage = Path(temp)
        atlas.save(stage / "KeyboardWarriorUI.png")
        (stage / "UIImageAtlasData.luau").write_text("\n".join([*entries, "}", ""]), encoding="utf-8")
        (stage / "KeyboardWarriorUI.png").replace(folder / "atlas/KeyboardWarriorUI.png")
        (stage / "UIImageAtlasData.luau").replace(shared / "UIImageAtlasData.luau")
    print(f"Packed {len(paths)} UI sprites into {SIZE}x{SIZE}")


if __name__ == "__main__":
    build()
