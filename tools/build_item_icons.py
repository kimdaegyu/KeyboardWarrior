"""Build item atlas pages and the matching Roblox slot map from an Excel Id column."""
import argparse
from pathlib import Path
from tempfile import TemporaryDirectory

from openpyxl import load_workbook
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CELL, GRID, PADDING = 64, 16, 2


def load_ids(sheet):
    book = load_workbook(sheet, read_only=True, data_only=True)
    try:
        rows = iter(book.worksheets[0].values)
        header = next(rows, ())
        if header.count("Id") != 1:
            raise ValueError("Expected one Id column in the first worksheet")
        column = header.index("Id")
        ids = set()
        for line, row in enumerate(rows, 2):
            if all(value is None for value in row):
                continue
            value = row[column]
            if type(value) is not int or not 0 < value < 2**53 or value in ids:
                raise ValueError(f"Row {line}: invalid or duplicate Id {value!r}")
            ids.add(value)
        if not ids:
            raise ValueError("The worksheet has no items")
        return sorted(ids)
    finally:
        book.close()


def build(sheet, source, root):
    ids = load_ids(sheet)
    atlas_dir = root / "assets/item-icons" / "atlas"
    shared = root / "src/ReplicatedStorage/Shared"
    atlas_dir.mkdir(parents=True, exist_ok=True)
    shared.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(dir=root) as staging:
        stage = Path(staging)
        pages = []
        side = CELL - 2 * PADDING
        for start in range(0, len(ids), GRID**2):
            page = Image.new("RGBA", (CELL * GRID, CELL * GRID))
            for slot, item in enumerate(ids[start:start + GRID**2]):
                with Image.open(source / f"{item}.png") as icon:
                    tile = icon.convert("RGBA").resize((side, side), Image.Resampling.LANCZOS)
                page.paste(tile, (slot % GRID * CELL + PADDING, slot // GRID * CELL + PADDING))
            path = stage / f"ItemIconAtlas_{len(pages) + 1}.png"
            page.save(path)
            pages.append(path)
        slots = "".join(f"\t\t[{item}] = {slot},\n" for slot, item in enumerate(ids))
        manifest = stage / "ItemIconSlots.luau"
        manifest.write_text(
            f"--!strict\n-- Generated by build_item_icons.py\nreturn {{\n"
            f"\tCellSize = {CELL},\n\tGrid = {GRID},\n\tPadding = {PADDING},\n"
            f"\tSlots = {{\n{slots}\t}} :: {{[number]: number}},\n}}\n", encoding="utf-8")
        for path in pages:
            path.replace(atlas_dir / path.name)
        manifest.replace(shared / manifest.name)
        for path in atlas_dir.glob("ItemIconAtlas_*.png"):
            number = path.stem.removeprefix("ItemIconAtlas_")
            if number.isdecimal() and int(number) > len(pages):
                path.unlink()
    print(f"Built {len(pages)} page(s) for {len(ids)} items")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sheet", type=Path, default=ROOT / "tables/ItemDataSheet.xlsx")
    parser.add_argument("--source", type=Path, default=ROOT / "assets/item-icons/source")
    args = parser.parse_args()
    build(args.sheet, args.source, ROOT)
